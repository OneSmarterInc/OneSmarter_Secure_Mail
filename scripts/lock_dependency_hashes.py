"""Generate wheel-only SHA-256 locks for exact pins from public PyPI metadata.

This preserves the reviewed version set; it does not upgrade or resolve versions.
pip --require-hashes verifies dependency completeness and downloaded artifacts.
"""

import argparse
import json
import re
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIN = re.compile(r"([A-Za-z0-9][A-Za-z0-9_.-]*)==([A-Za-z0-9_.+!-]+)")


def hashes(pin: str) -> list[str]:
    match = PIN.fullmatch(pin)
    if not match:
        raise ValueError(f"Expected an exact package==version pin: {pin}")
    name, version = match.groups()
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    request = urllib.request.Request(url, headers={"User-Agent": "OneSmarter-lock-generator/1"})
    with urllib.request.urlopen(request, timeout=30) as response:
        metadata = json.load(response)
    if metadata["info"]["version"] != version:
        raise ValueError(f"Unexpected release metadata for {pin}")
    result = sorted(
        {
            artifact["digests"]["sha256"]
            for artifact in metadata["urls"]
            if artifact["packagetype"] == "bdist_wheel" and not artifact["yanked"]
        }
    )
    if not result or any(not re.fullmatch(r"[0-9a-f]{64}", value) for value in result):
        raise ValueError(f"Missing or invalid wheel hashes for {pin}")
    return result


def render(source: Path) -> str:
    lines = source.read_text(encoding="utf-8").splitlines()
    pins = [line.strip() for line in lines if line.strip() and not line.startswith("#")]
    if len(pins) != len(set(pins)):
        raise ValueError("Duplicate dependency pins")
    with ThreadPoolExecutor(max_workers=8) as pool:
        releases = list(pool.map(hashes, pins))
    result = [
        "# Generated by python scripts/lock_dependency_hashes.py; do not edit hashes manually.",
        f"# Source: {source.name}; exact versions, non-yanked PyPI wheel SHA-256 digests.",
        "# Install with --require-hashes --only-binary=:all:; no source builds are permitted.",
    ]
    result.extend(line for line in lines if line.startswith("#"))
    for pin, values in zip(pins, releases, strict=True):
        result.append(pin + " \\")
        for index, digest in enumerate(values):
            result.append(
                "    --hash=sha256:" + digest + (" \\" if index < len(values) - 1 else "")
            )
    return "\n".join(result) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare without modifying files")
    args = parser.parse_args()
    # Generate both completely before writing either; metadata failures preserve existing locks.
    outputs = {
        ROOT / f"{name}.lock": render(ROOT / f"{name}.in")
        for name in ("requirements", "requirements-test")
    }
    for path, content in outputs.items():
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Lock differs from current release metadata: {path.name}")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
        print(f"Verified {path.name}: {content.count('--hash=sha256:')} wheel hashes")


if __name__ == "__main__":
    main()
